/**
 * Writes every migration into one SQL file that can be pasted into a SQL
 * console.
 *
 *   pnpm db:bundle
 *
 * The point is not just the DDL. The file also writes drizzle's bookkeeping
 * rows, so a database set up by hand is indistinguishable from one the migrator
 * built, and the next deployment applies only what is genuinely new instead of
 * trying to recreate tables that already exist.
 *
 * Regenerate it whenever a migration is added. It is derived, never edited.
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const FOLDER = "drizzle";
const OUTPUT = path.join(FOLDER, "schema-bundle.sql");

const journal = JSON.parse(
  fs.readFileSync(path.join(FOLDER, "meta", "_journal.json"), "utf8"),
);

const parts = [
  "-- Blackbook schema, every migration in order.",
  "--",
  "-- Generated by `pnpm db:bundle`. Do not edit; regenerate.",
  "-- Run against an empty database. Safe to run once, and only once.",
  "--",
  "-- The final section records these migrations as applied, so the application",
  "-- will not try to apply them again on its next start.",
  "",
  "BEGIN;",
  "",
];

const applied = [];

for (const entry of journal.entries) {
  const file = path.join(FOLDER, `${entry.tag}.sql`);
  const sql = fs.readFileSync(file, "utf8");

  // Drizzle hashes the raw file contents, so the hash has to be taken before
  // anything is stripped from it.
  const hash = crypto.createHash("sha256").update(sql).digest("hex");
  applied.push({ hash, when: entry.when });

  parts.push(
    `-- ${"-".repeat(70)}`,
    `-- ${entry.tag}`,
    `-- ${"-".repeat(70)}`,
    "",
    // `--> statement-breakpoint` is a SQL comment, so a console ignores it.
    sql.trimEnd(),
    "",
  );
}

parts.push(
  `-- ${"-".repeat(70)}`,
  "-- Migration bookkeeping",
  `-- ${"-".repeat(70)}`,
  "",
  'CREATE SCHEMA IF NOT EXISTS "drizzle";',
  "",
  'CREATE TABLE IF NOT EXISTS "drizzle"."__drizzle_migrations" (',
  "  id SERIAL PRIMARY KEY,",
  "  hash text NOT NULL,",
  "  created_at bigint",
  ");",
  "",
  'INSERT INTO "drizzle"."__drizzle_migrations" ("hash", "created_at") VALUES',
  applied
    .map(({ hash, when }) => `  ('${hash}', ${when})`)
    .join(",\n") + ";",
  "",
  "COMMIT;",
  "",
);

fs.writeFileSync(OUTPUT, parts.join("\n"), "utf8");

console.log(`Wrote ${OUTPUT}`);
console.log(`  ${journal.entries.length} migrations bundled`);
