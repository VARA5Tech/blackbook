-- Blackbook's schema, as one baseline.
--
-- Squashed from the six migrations the schema was built up through during
-- development. Two of those were corrections and are absorbed rather than
-- replayed: the audit trail's foreign keys are declared SET NULL in the
-- generated DDL below, and the append-only trigger appears once, in its final
-- form.
--
-- The live database has already run all six. The migrator decides what to
-- apply by comparing this journal entry's `when` against the newest row in
-- `drizzle.__drizzle_migrations`, never by hash, so the entry keeps the last of
-- those six timestamps: an existing database skips this file, and an empty one
-- builds the whole schema from it. The superseded rows are left in that
-- bookkeeping table, since only the newest is ever read.
--
-- Everything down to the search indexes is generated by drizzle-kit from
-- `src/db/schema`. Everything after is hand-written, because trigram indexes on
-- generated columns, PL/pgSQL functions, triggers and row-level security are
-- outside what a schema definition can express. Regenerating the first half
-- means re-appending the second.

